// Prints every confirm dialog text to ../HUB-DIALOG-TEXTS.md, straight from src/lib/confirm-notes/*.json, so the file never drifts.
// Run: node scripts/print-confirm-notes.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'

const dir = 'src/lib/confirm-notes'
const NOTES = {}
for (const f of readdirSync(dir).filter((x) => x.endsWith('.json')).sort()) Object.assign(NOTES, JSON.parse(readFileSync(`${dir}/${f}`, 'utf8')))
const keysSrc = readFileSync('src/lib/confirmActions.ts', 'utf8')
const ACTIONS = [...keysSrc.matchAll(/^\s+'([a-z-]+)': \{ label: '([^']+)'/gm)].map((m) => ({ key: m[1], label: m[2] })).filter((a) => a.key !== 'stage-backward')
const STAGES = ['New Lead', 'Dial 1', 'Dial 2', 'Quoting', 'Quote Sent', 'Follow-Up', 'Nurture', 'Quote Accepted', 'Inspection Required', 'Booking Required', 'Job Booked', 'Deposit Requested', 'Job Completed', 'Retention Claim']
const UNDO = 'Undo moves the job back, but cannot take back a message already sent.'

const block = (title, buttons, note) => {
  const out = [`**${title}**`, '']
  if (!note) out.push('(no list)', '')
  else {
    if (note.lines.length) out.push('What happens:', ...note.lines.map((l) => `- ${l}`), '')
    if (note.stops.length) out.push('Stops:', ...note.stops.map((l) => `- ${l}`), '')
    if (note.sends) out.push(UNDO, '')
  }
  out.push(`Buttons: Cancel (focus), ${buttons}`, '')
  return out.join('\n')
}

const md = ['# Hub dialog texts (generated)', '',
  'Generated by scripts/print-confirm-notes.mjs from src/lib/confirm-notes/*.json. Do not edit this file: edit the JSON, then run the script.',
  'Every stage move reads: "Move <job> from X to Y?". Cancel has the focus, Escape cancels.', '', '## Stage moves (into the stage)', '']
for (const s of STAGES) md.push(`### ${s}`, '', block(`Move <job> from <stage> to ${s}?`, 'Yes, move it', NOTES[s]))
md.push('## End states', '', '### Won', '', block('Mark <job> as won?', 'Yes, mark won', NOTES.Won), '### Lost', '', block('Mark <job> as lost?', 'Yes, mark lost', NOTES.Lost))
md.push('## Other actions', '')
for (const a of ACTIONS) {
  if (['stage-change', 'mark-won', 'mark-lost', 'tag-add', 'tag-remove'].includes(a.key)) continue
  md.push(`### ${a.label} (${a.key})`, '', block(a.label + '?', 'Yes', NOTES[a.key]))
}
md.push('## Tags', '')
for (const k of Object.keys(NOTES).filter((k) => k.startsWith('tag-')).sort()) md.push(`### ${k}`, '', block(k.startsWith('tag-add') ? 'Add this tag?' : 'Remove this tag?', 'Yes', NOTES[k]))
const missing = [...STAGES, 'Won', 'Lost', ...ACTIONS.map((a) => a.key).filter((k) => !['stage-change', 'mark-won', 'mark-lost', 'tag-add', 'tag-remove'].includes(k))].filter((k) => !NOTES[k])
md.push('## Not written yet', '', missing.length ? missing.map((k) => `- ${k}`).join('\n') : 'Nothing: every stage, Won, Lost and action has a text.', '')
writeFileSync('../HUB-DIALOG-TEXTS.md', md.join('\n'))
console.log(`written ../HUB-DIALOG-TEXTS.md, ${Object.keys(NOTES).length} entries, missing: ${missing.length}`)
